import assert from "node:assert/strict";
import * as XLSX from "xlsx";
import JSZip from "jszip";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { runWorkspaceSpreadsheetSnapshot } from "../src/persistent-room-shelf-reading.js";

const workbook = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet([["Invented value", 42], ["Another row", true]]), "Example");
const snapshot = Buffer.from(XLSX.write(workbook, { type: "buffer", bookType: "xlsx" }));
const result = await runWorkspaceSpreadsheetSnapshot(snapshot, new AbortController().signal);
assert.equal(result.ok, true);
assert.equal(result.result?.kind, "spreadsheet");
assert.equal(result.result?.workbook.sheets[0].name, "Example");
assert.equal(result.result?.workbook.sheets[0].cells[0].text, "Invented value");
assert.equal(result.result?.workbook.sheets[0].cells[1].text, "42");
const malformed = await runWorkspaceSpreadsheetSnapshot(Buffer.from("invented invalid workbook"), new AbortController().signal);
assert.equal(malformed.ok, false);
assert.equal(malformed.code, "damaged_file");
const oversized = await runWorkspaceSpreadsheetSnapshot(Buffer.alloc(26_214_401), new AbortController().signal);
assert.equal(oversized.ok, false);
assert.equal(oversized.code, "file_too_large");
const controller = new AbortController();
controller.abort();
const aborted = await runWorkspaceSpreadsheetSnapshot(snapshot, controller.signal);
assert.equal(aborted.ok, false);
assert.equal(aborted.code, "preview_aborted");
const sparse = XLSX.utils.book_new();
const wideSheet = XLSX.utils.aoa_to_sheet([["Start"]]);
XLSX.utils.sheet_add_aoa(wideSheet, [["Far"]], { origin: "Z10000" });
XLSX.utils.book_append_sheet(sparse, wideSheet, "Large grid");
const complex = await runWorkspaceSpreadsheetSnapshot(Buffer.from(XLSX.write(sparse, { type: "buffer", bookType: "xlsx" })), new AbortController().signal);
assert.equal(complex.ok, false);
assert.equal(complex.code, "preview_too_complex");
const longZip = await JSZip.loadAsync(snapshot);
const sheetXml = await longZip.file("xl/worksheets/sheet1.xml")!.async("string");
longZip.file("xl/worksheets/sheet1.xml", sheetXml.replace("Invented value", "A".repeat(32_768)));
const longText = await runWorkspaceSpreadsheetSnapshot(await longZip.generateAsync({ type: "nodebuffer", compression: "STORE" }), new AbortController().signal);
assert.equal(longText.ok, false);
assert.equal(longText.code, "preview_too_complex");
const zip = new JSZip();
zip.file("invented.xml", "A".repeat(1_000_000));
const compressed = await zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE" });
const expanded = await runWorkspaceSpreadsheetSnapshot(compressed, new AbortController().signal);
assert.equal(expanded.ok, false);
assert.equal(expanded.code, "expanded_content_too_large");
const running = [runWorkspaceSpreadsheetSnapshot(snapshot, new AbortController().signal), runWorkspaceSpreadsheetSnapshot(snapshot, new AbortController().signal)];
const busy = await runWorkspaceSpreadsheetSnapshot(snapshot, new AbortController().signal);
assert.equal(busy.code, "preview_busy");
assert((await Promise.all(running)).every((entry) => entry.ok));
const previousTemp = { TMPDIR: process.env.TMPDIR, TEMP: process.env.TEMP, TMP: process.env.TMP };
const testTemp = fs.mkdtempSync(path.join(os.tmpdir(), "spreadsheet-cleanup-test-"));
process.env.TMPDIR = testTemp;
process.env.TEMP = testTemp;
process.env.TMP = testTemp;
assert.equal((await runWorkspaceSpreadsheetSnapshot(snapshot, new AbortController().signal)).ok, true);
assert.deepEqual(fs.readdirSync(testTemp), []);
assert.equal((await runWorkspaceSpreadsheetSnapshot(Buffer.from("invalid"), new AbortController().signal)).code, "damaged_file");
assert.deepEqual(fs.readdirSync(testTemp), []);
const midFlight = new AbortController();
const cancelled = runWorkspaceSpreadsheetSnapshot(snapshot, midFlight.signal);
midFlight.abort();
assert.equal((await cancelled).code, "preview_aborted");
assert.deepEqual(fs.readdirSync(testTemp), []);
for (const [key, value] of Object.entries(previousTemp)) {
	if (value === undefined) delete process.env[key];
	else process.env[key] = value;
}
fs.rmSync(testTemp, { recursive: true, force: true });
console.log("workspace spreadsheet snapshot smoke passed");
