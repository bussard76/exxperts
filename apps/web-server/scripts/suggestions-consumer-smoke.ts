// Exercise the real room composer with synthetic frames on its existing socket.
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import fs from "node:fs";
import http from "node:http";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { SMOKE_AUTH_TOKEN, SMOKE_SERVER_AUTH_ENV, SMOKE_SERVER_SPAWN_TREE_OPTIONS, smokeHomeEnv, stopSmokeServer, freePort, waitForServer } from "./smoke-server-process.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const webServerDir = path.join(root, "apps/web-server");
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), "suggestions-consumer-"));
const home = path.join(temporary, "home");
const agentDir = path.join(home, ".exxperts/agent");
const roomsDir = path.join(home, ".exxperts/app/personalized-agents");
fs.mkdirSync(agentDir, { recursive: true });
fs.mkdirSync(roomsDir, { recursive: true });
process.env.HOME = home;
process.env.USERPROFILE = home;
process.env.EXXPERTS_CODING_AGENT_DIR = agentDir;
process.env.EXXETA_PERSISTENT_AGENTS_ROOT = roomsDir;
const gateway = http.createServer((req, res) => { req.resume(); res.writeHead(200, { "content-type": "application/json" }).end("{}"); });
const gatewayPort = await freePort();
await new Promise<void>((resolve) => gateway.listen(gatewayPort, "127.0.0.1", resolve));
fs.writeFileSync(path.join(agentDir, "models.json"), JSON.stringify({ providers: { "fake-gpt": { name: "Fake GPT", baseUrl: `http://127.0.0.1:${gatewayPort}/v1`, api: "openai-completions", models: [{ id: "gpt-fake", name: "GPT Fake", reasoning: true, input: ["text"], contextWindow: 128000, maxTokens: 16000 }] } } }));
fs.writeFileSync(path.join(agentDir, "auth.json"), JSON.stringify({ "fake-gpt": { type: "api_key", key: "synthetic-consumer-test" } }));
const appDir = path.join(home, ".exxperts/app");
fs.writeFileSync(path.join(appDir, "custom-ai-profiles.json"), JSON.stringify({ version: 1, profiles: [{ id: "custom-fake-gpt", providerId: "fake-gpt", label: "Fake GPT", roomModels: ["gpt-fake"], learnModel: "gpt-fake", reviewMemoryModel: "gpt-fake" }] }));
fs.writeFileSync(path.join(appDir, "persistent-agent-ai-profile.json"), JSON.stringify({ profileId: "custom-fake-gpt" }));
const agents = await import("../src/persistent-agents.js");
const room = agents.createPersistentAgentFromScaffoldInput({ displayName: "Example Room", userName: "Example User", preferredUserAddress: "Example User" }).agent.agentId;
const roomModels = await import("../src/room-models.js");
roomModels.writeRoomModels(room, { conversation: { provider: "fake-gpt", model: "gpt-fake" } });
const other = agents.createPersistentAgentFromScaffoldInput({ displayName: "Other Room", userName: "Example User", preferredUserAddress: "Example User" }).agent.agentId;
roomModels.writeRoomModels(other, { conversation: { provider: "fake-gpt", model: "gpt-fake" } });
const port = await freePort();
const base = `http://127.0.0.1:${port}`;
const server = spawn("npx", ["tsx", "src/index.ts"], {
 cwd: webServerDir, ...SMOKE_SERVER_SPAWN_TREE_OPTIONS,
 env: smokeHomeEnv(home, { PORT: String(port), ...SMOKE_SERVER_AUTH_ENV, EXXETA_HOME: root, EXXPERTS_CODING_AGENT_DIR: agentDir, EXXETA_PERSISTENT_AGENTS_ROOT: roomsDir }) as NodeJS.ProcessEnv,
});
try {
 await waitForServer(server, base, 30_000);
 const browser = await chromium.launch();
 try {
  const page = await browser.newPage();
  await page.addInitScript({ content: `
   const Original = window.WebSocket;
   window.WebSocket = class extends Original {
    constructor(url, protocols) {
     super(url, protocols);
     this.addEventListener("message", (event) => {
      const frame = JSON.parse(event.data);
      if (frame.type === "ready" && frame.persistentAgentId) Object.assign(window, { testRoomSocket: this, testRoom: frame.persistentAgentId, testThread: frame.conversationId });
     });
    }
   };
  ` });
  await page.goto(`${base}/auth/session?token=${SMOKE_AUTH_TOKEN}`);
  await page.waitForLoadState("networkidle");
  const dismiss = page.locator(".whats-new-close");
  if (await dismiss.count()) await dismiss.click();
  await page.locator(".persistent-agent-card").filter({ hasText: "Example Room" }).getByRole("button", { name: "Enter" }).click();
  const box = page.locator(".composer textarea").first();
  await box.waitFor();
  await page.waitForFunction(() => Boolean((window as any).testThread), null, { timeout: 8000 });
  const frame = async (payload: Record<string, unknown>) => page.evaluate((value) => {
   const w = window as any;
   w.testRoomSocket.dispatchEvent(new MessageEvent("message", { data: JSON.stringify({ roomId: w.testRoom, threadId: w.testThread, ...value }) }));
  }, payload);
  const placeholder = () => box.getAttribute("placeholder");
  const ordinary = await placeholder();
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Alpha", "Beta", "Gamma"] });
  assert.equal(await placeholder(), ordinary, "suggestions without a live completion are rejected");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-one", roomId: "other-room" });
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Wrong room"] });
  assert.equal(await placeholder(), ordinary, "another room cannot establish a live completion");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-one", threadId: "other-thread" });
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Wrong thread"] });
  assert.equal(await placeholder(), ordinary, "another thread cannot establish a live completion");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-one" });
  await frame({ type: "suggestions", answerId: "old-answer", items: ["Stale"] });
  assert.equal(await placeholder(), ordinary, "a different answer is rejected");
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Alpha", "Beta", "Gamma"] });
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") === "Alpha");
  const describedBy = await box.getAttribute("aria-describedby");
  assert.ok(describedBy, "suggestion has an accessible hint");
  assert.match(await page.locator(`[id="${describedBy}"]`).innerText(), /Tab: weiter, →: übernehmen/);
  await box.fill("@other");
  await page.getByRole("listbox").waitFor();
  await box.press("Tab");
  assert.match(await box.inputValue(), /@other-room/, "mention picker owns Tab");
  await box.fill("");
  await box.focus();
  await box.press("Tab");
  assert.equal(await placeholder(), "Beta");
  await box.fill("A draft");
  await box.fill("");
  assert.equal(await placeholder(), "Beta", "typing and clearing keeps the selection");
  const composing = await box.evaluate((node) => node.dispatchEvent(new KeyboardEvent("keydown", { key: "Tab", bubbles: true, cancelable: true, isComposing: true })));
  assert.equal(composing, true, "IME owns Tab");
  assert.equal(await placeholder(), "Beta");
  await box.press("ArrowRight");
  assert.equal(await box.inputValue(), "Beta");
  await box.fill("");
  assert.equal(await placeholder(), "Gamma");
  await box.press("Tab");
  assert.equal(await placeholder(), "Alpha");
  await box.press("Shift+Tab");
  assert.equal(await placeholder(), "Gamma");
  await box.press("ArrowRight");
  await box.fill("");
  assert.equal(await placeholder(), "Alpha");
  await box.press("Tab");
  assert.notEqual(await box.evaluate((node) => node === document.activeElement), true, "one remaining suggestion leaves Tab to focus navigation");
  await box.focus();
  await box.press("ArrowRight");
  await box.fill("");
  assert.equal(await placeholder(), ordinary);
  await box.press("Tab");
  assert.notEqual(await box.evaluate((node) => node === document.activeElement), true, "zero suggestions leave Tab to focus navigation");
  await frame({ type: "answer_lifecycle", phase: "invalidate" });
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Stale"] });
  assert.equal(await placeholder(), ordinary, "invalidation rejects late results");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-two" });
  await frame({ type: "suggestions", answerId: "answer-one", items: ["Stale"] });
  assert.equal(await placeholder(), ordinary, "a newer completion rejects an older result");
  await frame({ type: "suggestions", answerId: "answer-two", items: ["New idea", "Another idea"] });
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") === "New idea");
  await box.focus();
  await box.press("Escape");
  assert.equal(await placeholder(), ordinary, "Escape hides suggestions");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-three" });
  await frame({ type: "suggestions", answerId: "answer-three", items: ["Fresh idea"] });
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") === "Fresh idea");
  await page.evaluate(() => (window as any).testRoomSocket.close());
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") !== "Fresh idea");
  await page.waitForFunction(() => (window as any).testRoomSocket.readyState === WebSocket.OPEN);
  await frame({ type: "suggestions", answerId: "answer-three", items: ["Stale after reconnect"] });
  assert.notEqual(await placeholder(), "Stale after reconnect", "reconnect cannot reuse the previous completion");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "answer-four" });
  await frame({ type: "suggestions", answerId: "answer-four", items: ["Send clears me"] });
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") === "Send clears me");
  await box.fill("A new prompt");
  await box.press("Enter");
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") !== "Send clears me");
  await frame({ type: "suggestions", answerId: "answer-four", items: ["Late after send"] });
  assert.notEqual(await placeholder(), "Late after send", "sending invalidates immediately");
  await page.reload();
  await box.waitFor();
  assert.notEqual(await placeholder(), "Send clears me", "suggestions are not persisted or replayed after reload");
  await page.waitForFunction(() => Boolean((window as any).testThread));
  await frame({ type: "turn_reattach" });
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "replayed-answer" });
  await frame({ type: "suggestions", answerId: "replayed-answer", items: ["Replayed suggestion"] });
  await frame({ type: "turn_reattach_replay_done" });
  assert.notEqual(await placeholder(), "Replayed suggestion", "replayed completion and suggestions are ignored");
  await page.locator(".sidebar-home-btn").click();
  await page.locator(".persistent-agent-card").filter({ hasText: "Other Room" }).getByRole("button", { name: "Enter" }).click();
  await box.waitFor();
  assert.notEqual(await placeholder(), "Send clears me", "changing rooms clears suggestions");
  await page.waitForFunction(() => (window as any).testRoom === "other-room");
  await frame({ type: "answer_lifecycle", phase: "complete", answerId: "other-answer" });
  await frame({ type: "suggestions", answerId: "other-answer", items: ["Old thread suggestion"] });
  await page.waitForFunction(() => document.querySelector(".composer textarea")?.getAttribute("placeholder") === "Old thread suggestion");
  const oldThread = await page.evaluate(() => (window as any).testThread);
  await page.getByRole("button", { name: "Forget", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Forget", exact: true }).click();
  await page.waitForFunction((previous) => (window as any).testThread !== previous, oldThread);
  assert.notEqual(await placeholder(), "Old thread suggestion", "changing threads clears suggestions");
  await frame({ type: "suggestions", answerId: "other-answer", items: ["Late old thread"] });
  assert.notEqual(await placeholder(), "Late old thread", "old-thread completion cannot authorize a new thread");
 } finally { await browser.close(); }
} finally {
 await stopSmokeServer(server);
 await new Promise<void>((resolve) => gateway.close(() => resolve()));
 fs.rmSync(temporary, { recursive: true, force: true });
}
