import { assert, createRoom, endFailingCase, FAILING_MARKER, gatewayRequests, putThread, reportDetachedFailure, requestJson, setHoldSuggestionResponse, setSuggestionResponse, SLOW_MARKER, startDetachedServer, stopDetachedServer, waitDetached, waitUntil, WsHarness } from "./persistent-room-detached-turn-setup.js";

try {
	await startDetachedServer(undefined, "suggest-model");
	setSuggestionResponse('["  Next question?  ", "Another\\nquestion", "Next question?"]');
	const room = await createRoom("Suggestion Room");
	const thread = "suggestion_thread";
	await putThread(room, thread, []);
	const socket = await WsHarness.connect(room, thread);
	await socket.waitFor((frame) => frame.type === "ready", "ready");
	socket.send({ type: "prompt", text: "What comes next?" });
	const invalidate = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "invalidate", "invalidation", 0, 5000);
	const complete = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "completion", invalidate, 5000);
	assert(socket.frames[complete].roomId === room && socket.frames[complete].threadId === thread && typeof socket.frames[complete].answerId === "string", "completion carries its room, thread and answer identity");
	const result = await socket.waitFor((frame) => frame.type === "suggestions", "suggestions", complete, 5000);
	assert(JSON.stringify(socket.frames[result]) === JSON.stringify({ type: "suggestions", roomId: room, threadId: thread, answerId: socket.frames[complete].answerId, items: ["Next question?", "Another question"] }), "suggestions carry the matching identity and normalized items");
	const request = gatewayRequests.find((entry) => entry.suggestion)?.request;
	assert(gatewayRequests.find((entry) => entry.suggestion)?.model === "suggest-model", "suggestions use the answering provider's configured Memorize model");
	assert(request?.maxTokens === 200 && (!request.tools || (Array.isArray(request.tools) && request.tools.length === 0)), "the suggestion call is tool-less and capped at 200 output tokens");
	assert(JSON.stringify(request?.messages).includes("What comes next?") && JSON.stringify(request?.messages).includes("Quick answer."), "the suggestion call contains the completed exchange");
	const usage = await requestJson(`/api/usage?agent=${room}`);
	assert(usage.body.byAgent.some((entry: any) => entry.agent === room && entry.kinds.suggestions?.turns === 1), "suggestion tokens are recorded under the room's suggestions category");
	await putThread(room, thread, [
		{ kind: "user", id: "first-user", text: "What comes next?" },
		{ kind: "assistant", id: "first-answer", text: "Quick answer." },
		{ kind: "tool", id: "private-tool", name: "fake", result: "excluded synthetic tool result" },
	]);
	const priorRequests = gatewayRequests.length;
	socket.send({ type: "prompt", text: "Another question", shown: { text: "Another question", files: [] } });
	const secondComplete = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "second completion", result + 1);
	await socket.waitFor((frame) => frame.type === "suggestions", "second suggestions", secondComplete);
	const secondRequest = gatewayRequests.slice(priorRequests).find((entry) => entry.suggestion)?.request;
	const secondContext = JSON.stringify(secondRequest?.messages);
	assert(secondContext.includes("What comes next?") && secondContext.includes("Another question"), "a provably completed earlier exchange is included");
	assert(!secondContext.includes("excluded synthetic tool result"), "tool results are excluded from suggestion context");
	setSuggestionResponse('["partial"');
	socket.send({ type: "prompt", text: "A final question" });
	const invalidComplete = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "invalid JSON completion", secondComplete + 1);
	const invalidResult = await socket.waitFor((frame) => frame.type === "suggestions", "invalid JSON result", invalidComplete);
	assert(JSON.stringify(socket.frames[invalidResult].items) === "[]", "invalid JSON yields an empty list");
	setSuggestionResponse(JSON.stringify(["x".repeat(250), " ", "second", "third", "fourth"]));
	socket.send({ type: "prompt", text: "Give me short ideas" });
	const boundedComplete = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "bounded completion", invalidResult + 1);
	const boundedResult = await socket.waitFor((frame) => frame.type === "suggestions", "bounded result", boundedComplete);
	assert(JSON.stringify(socket.frames[boundedResult].items) === JSON.stringify(["x".repeat(200), "second", "third"]), "suggestions discard empty entries, cap length and keep at most three");
	setSuggestionResponse('["Next question?"]');
	const longRequests = gatewayRequests.length;
	socket.send({ type: "prompt", text: `Long question ${"x".repeat(5000)}` });
	const longComplete = await socket.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "long completion", boundedResult + 1);
	await socket.waitFor((frame) => frame.type === "suggestions", "long result", longComplete);
	const longRequest = gatewayRequests.slice(longRequests).find((entry) => entry.suggestion)?.request;
	const longContent = longRequest?.messages.find((entry: any) => entry.role === "user")?.content;
	const longContext = typeof longContent === "string" ? longContent : longContent?.map((part: any) => part.text ?? "").join("");
	assert(typeof longContext === "string" && longContext.length <= 4000 && longContext.includes("Quick answer."), "long context keeps the newest text within 4000 string units");
	socket.close();
	const reconnected = await WsHarness.connect(room, thread);
	await reconnected.waitFor((frame) => frame.type === "ready", "reconnected ready");
	await new Promise((resolve) => setTimeout(resolve, 250));
	assert(!reconnected.frames.some((frame) => frame.type === "answer_lifecycle" || frame.type === "suggestions"), "completion and suggestions are not replayed after reconnect");
	reconnected.close();

	const adoptedRoom = await createRoom("Suggestion Adoption Room");
	const adoptedThread = "suggestion_adoption";
	await putThread(adoptedRoom, adoptedThread, []);
	const first = await WsHarness.connect(adoptedRoom, adoptedThread);
	await first.waitFor((frame) => frame.type === "ready", "first ready");
	first.send({ type: "prompt", text: `Continue the story ${SLOW_MARKER}` });
	await first.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "invalidate", "first invalidation");
	await first.waitFor((frame) => frame.type === "event" && frame.event?.type === "message_update", "first answer chunk");
	first.close();
	await waitDetached(adoptedRoom, "adoption");
	const second = await WsHarness.connect(adoptedRoom, adoptedThread);
	await second.waitFor((frame) => frame.type === "turn_reattach", "adopted answer");
	const third = await WsHarness.connect(adoptedRoom, adoptedThread);
	await third.waitFor((frame) => frame.type === "turn_reattach", "takeover answer");
	await second.waitFor((frame) => frame.type === "error" && frame.code === "room_displaced", "displaced adopter");
	const before = second.frames.length;
	[...gatewayRequests].reverse().find((request) => request.slow && !request.finished)?.release();
	const adoptedComplete = await third.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "adopted completion");
	const adoptedResult = await third.waitFor((frame) => frame.type === "suggestions", "adopted suggestions", adoptedComplete);
	assert(third.frames[adoptedResult].answerId === third.frames[adoptedComplete].answerId, "adopted result matches live completion");
	assert(!second.frames.slice(before).some((frame) => frame.type === "answer_lifecycle" || frame.type === "suggestions"), "displaced adopter receives no lifecycle or suggestion frames");
	third.close();

	const staleRoom = await createRoom("Suggestion Cancellation Room");
	const staleThread = "suggestion_cancellation";
	await putThread(staleRoom, staleThread, []);
	const current = await WsHarness.connect(staleRoom, staleThread);
	await current.waitFor((frame) => frame.type === "ready", "cancellation ready");
	setHoldSuggestionResponse(true);
	current.send({ type: "prompt", text: "First question" });
	const oldComplete = await current.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "old completion");
	const oldId = current.frames[oldComplete].answerId;
	const countBeforeOld = gatewayRequests.length;
	await waitUntil(() => gatewayRequests.some((request, i) => i >= countBeforeOld - 1 && request.suggestion && !request.finished), "held suggestion request", 10000);
	const oldRequest = [...gatewayRequests].reverse().find((request) => request.suggestion && !request.finished)!;
	setHoldSuggestionResponse(false);
	current.send({ type: "prompt", text: "Second question" });
	const nextInvalidation = await current.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "invalidate", "new invalidation", oldComplete + 1);
	const nextComplete = await current.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "new completion", nextInvalidation);
	assert(current.frames[nextComplete].answerId !== oldId, "queued answer has a different identity");
	oldRequest.release();
	const nextResult = await current.waitFor((frame) => frame.type === "suggestions", "new result", nextComplete);
	assert(current.frames[nextResult].answerId === current.frames[nextComplete].answerId, "only the new answer receives a result");
	assert(!current.frames.slice(nextInvalidation).some((frame) => frame.type === "suggestions" && frame.answerId === oldId), "new prompt invalidates a delayed result");
	current.close();

	const unledRoom = await createRoom("Suggestion Unled Room");
	const unledThread = "suggestion_unled";
	await putThread(unledRoom, unledThread, []);
	const unled = await WsHarness.connect(unledRoom, unledThread);
	await unled.waitFor((frame) => frame.type === "ready", "unled ready");
	const unledBefore = gatewayRequests.length;
	unled.send({ type: "prompt", text: `Finish without a window ${SLOW_MARKER}` });
	await unled.waitFor((frame) => frame.type === "event" && frame.event?.type === "message_update", "unled answer chunk");
	unled.close();
	await waitDetached(unledRoom, "unled");
	const unledRequest = gatewayRequests.slice(unledBefore).find((request) => request.slow)!;
	unledRequest.release();
	await waitUntil(() => unledRequest.finished, "unled answer finished", 10000);
	await new Promise((resolve) => setTimeout(resolve, 500));
	assert(!gatewayRequests.slice(unledBefore).some((request) => request.suggestion), "an answer without a leading window makes no suggestion call");

	const stoppedRoom = await createRoom("Suggestion Stopped Room");
	const stoppedThread = "suggestion_stopped";
	await putThread(stoppedRoom, stoppedThread, []);
	const stopped = await WsHarness.connect(stoppedRoom, stoppedThread);
	await stopped.waitFor((frame) => frame.type === "ready", "stopped ready");
	const stoppedBefore = gatewayRequests.length;
	stopped.send({ type: "prompt", text: `Stop this answer ${SLOW_MARKER}` });
	await stopped.waitFor((frame) => frame.type === "event" && frame.event?.type === "message_update", "stopped answer chunk");
	stopped.send({ type: "abort" });
	await stopped.waitFor((frame) => frame.type === "event" && frame.event?.type === "agent_end", "stopped answer end");
	assert(!stopped.frames.some((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete"), "a stopped answer publishes no completion");
	assert(!gatewayRequests.slice(stoppedBefore).some((request) => request.suggestion), "a stopped answer makes no suggestion call");

	const retryRoom = await createRoom("Suggestion Retry Room");
	const retryThread = "suggestion_retry";
	await putThread(retryRoom, retryThread, []);
	const retry = await WsHarness.connect(retryRoom, retryThread);
	await retry.waitFor((frame) => frame.type === "ready", "retry ready");
	const retryTag = `${FAILING_MARKER}:suggestions`;
	const retryBefore = gatewayRequests.length;
	retry.send({ type: "prompt", text: `Retry this answer ${retryTag}` });
	await retry.waitFor((frame) => frame.type === "event" && frame.event?.type === "auto_retry_start", "retry intermediate");
	assert(!retry.frames.some((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete"), "retry intermediate publishes no completion");
	assert(!gatewayRequests.slice(retryBefore).some((request) => request.suggestion), "retry intermediate makes no suggestion call");
	endFailingCase(retryTag);
	const retryComplete = await retry.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "successful retry completion", 0, 30000);
	const retryResult = await retry.waitFor((frame) => frame.type === "suggestions", "successful retry result", retryComplete);
	assert(retry.frames[retryResult].answerId === retry.frames[retryComplete].answerId, "successful retry publishes one correlated result");
	assert(retry.frames.filter((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete").length === 1, "only the successful retry completes");

	const overlapRoom = await createRoom("Suggestion Overlap Room");
	const overlapThread = "suggestion_overlap";
	await putThread(overlapRoom, overlapThread, []);
	const overlap = await WsHarness.connect(overlapRoom, overlapThread);
	await overlap.waitFor((frame) => frame.type === "ready", "overlap ready");
	const overlapBefore = gatewayRequests.length;
	overlap.send({ type: "prompt", text: `First answer ${SLOW_MARKER}` });
	await overlap.waitFor((frame) => frame.type === "event" && frame.event?.type === "message_update", "overlap answer chunk");
	const frameBeforePrompt = overlap.frames.length;
	overlap.send({ type: "prompt", text: "A newer prompt" });
	await overlap.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "invalidate", "overlap invalidation", frameBeforePrompt);
	gatewayRequests.slice(overlapBefore).find((entry) => entry.slow)!.release();
	await overlap.waitFor((frame) => frame.type === "event" && frame.event?.type === "agent_end", "overlap end");
	assert(!overlap.frames.slice(frameBeforePrompt).some((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete"), "a newer prompt prevents an older completion from reviving suggestions");
	assert(!gatewayRequests.slice(overlapBefore).some((entry) => entry.suggestion), "a superseded answer does not start generation");

	const queuedRoom = await createRoom("Suggestion Queue Room");
	const queuedThread = "suggestion_queue";
	await putThread(queuedRoom, queuedThread, []);
	const queued = await WsHarness.connect(queuedRoom, queuedThread);
	await queued.waitFor((frame) => frame.type === "ready", "queue ready");
	queued.send({ type: "prompt", text: "An earlier question" });
	const priorComplete = await queued.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "prior completion");
	await queued.waitFor((frame) => frame.type === "suggestions", "prior result", priorComplete);
	const queuedBefore = gatewayRequests.length;
	queued.send({ type: "prompt", text: `A slow question ${SLOW_MARKER}` });
	await queued.waitFor((frame) => frame.type === "event" && frame.event?.type === "message_update", "queue first chunk", priorComplete + 1);
	queued.send({ type: "steer", id: "queued-next", text: "A queued question" });
	await queued.waitFor((frame) => frame.type === "steer_waiting" && frame.id === "queued-next", "queued message accepted");
	const firstQueuedRequest = gatewayRequests.slice(queuedBefore).find((entry) => entry.slow)!;
	firstQueuedRequest.release();
	await waitUntil(() => gatewayRequests.slice(queuedBefore).filter((entry) => entry.slow && !entry.suggestion).length >= 2, "queued answer begins", 10000);
	gatewayRequests.slice(queuedBefore).filter((entry) => entry.slow && !entry.suggestion)[1]!.release();
	const queuedComplete = await queued.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "queued completion", priorComplete + 1);
	const queuedResult = await queued.waitFor((frame) => frame.type === "suggestions", "queued result", queuedComplete);
	assert(queued.frames[queuedComplete].answerId !== queued.frames[priorComplete].answerId && queued.frames[queuedResult].answerId === queued.frames[queuedComplete].answerId, "queued answers receive a fresh identity and matching result");
	assert(queued.frames.slice(priorComplete + 1, queuedComplete).every((frame) => frame.type !== "answer_lifecycle" || frame.phase !== "complete"), "only the latest queued answer completes");

	const takeoverRoom = await createRoom("Suggestion Completion Takeover Room");
	const takeoverThread = "suggestion_completion_takeover";
	await putThread(takeoverRoom, takeoverThread, []);
	const owner = await WsHarness.connect(takeoverRoom, takeoverThread);
	await owner.waitFor((frame) => frame.type === "ready", "takeover owner ready");
	setHoldSuggestionResponse(true);
	const takeoverBefore = gatewayRequests.length;
	owner.send({ type: "prompt", text: "Wait for a suggestion" });
	const ownerCompletion = await owner.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "takeover completion");
	await waitUntil(() => gatewayRequests.slice(takeoverBefore).some((entry) => entry.suggestion && !entry.finished), "takeover held request", 10000);
	const takeoverRequest = gatewayRequests.slice(takeoverBefore).find((entry) => entry.suggestion)!;
	const successor = await WsHarness.connect(takeoverRoom, takeoverThread);
	await successor.waitFor((frame) => frame.type === "ready", "takeover successor ready");
	takeoverRequest.release();
	await new Promise((resolve) => setTimeout(resolve, 500));
	assert(!owner.frames.slice(ownerCompletion + 1).some((frame) => frame.type === "suggestions"), "former owner receives no delayed suggestion after takeover");
	assert(!successor.frames.some((frame) => frame.type === "answer_lifecycle" || frame.type === "suggestions"), "a new owner does not receive a completion it did not observe live");
	setHoldSuggestionResponse(false);

	const deadlineRoom = await createRoom("Suggestion Deadline Room");
	const deadlineThread = "suggestion_deadline";
	await putThread(deadlineRoom, deadlineThread, []);
	const deadline = await WsHarness.connect(deadlineRoom, deadlineThread);
	await deadline.waitFor((frame) => frame.type === "ready", "deadline ready");
	setHoldSuggestionResponse(true);
	const deadlineBefore = gatewayRequests.length;
	deadline.send({ type: "prompt", text: "A short question" });
	const deadlineComplete = await deadline.waitFor((frame) => frame.type === "answer_lifecycle" && frame.phase === "complete", "deadline completion");
	await waitUntil(() => gatewayRequests.slice(deadlineBefore).some((entry) => entry.suggestion), "deadline suggestion request", 10000);
	const deadlineRequest = gatewayRequests.slice(deadlineBefore).find((entry) => entry.suggestion)!;
	await waitUntil(() => deadlineRequest.aborted, "suggestion deadline abort", 15000);
	assert(!deadline.frames.slice(deadlineComplete + 1).some((frame) => frame.type === "suggestions"), "a timed out suggestion call is silent");
	setHoldSuggestionResponse(false);
} catch (error) {
	reportDetachedFailure(error);
} finally {
	await stopDetachedServer();
}
